import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import {configuredQueue} from './test-support/registered-queue.mjs';
test('reconnect, restart and duplicate receipts do not dispatch a task twice', t => {
  const dir = mkdtempSync(join(tmpdir(), 'queue-test-'));
  t.after(() => rmSync(dir, { recursive: true, force: true }));
  const db = join(dir, 'queue.db');
  let q = configuredQueue(db);
  const spec = {target:'bench.code', prompt:'Check the checkout', requestId:'phone-1'};
  const task = q.submit(spec);
  assert.equal(q.submit(spec).id, task.id);
  assert.throws(() => q.submit({...spec,prompt:'different input'}));
  assert.equal(q.claim('desk.code'), null);
  assert.equal(q.claim('bench.code').id, task.id);
  q.close(); q = configuredQueue(db);
  assert.equal(q.claim('bench.code').id, task.id);
  assert.throws(() => q.finish('desk.code', {id:task.id, state:'succeeded', result:'no'}));
  const receipt = {id:task.id,state:'succeeded',result:'ok'};
  q.finish('bench.code',receipt); q.finish('bench.code',receipt);
  assert.equal(q.get(task.id).result,'ok');
  assert.equal(q.claim('bench.code'),null);
  const cancelled = q.submit({...spec,requestId:'phone-2'});
  assert.equal(q.cancel(cancelled.id).state,'cancelled');
  assert.equal(q.claim('bench.code'),null);
  const running = q.submit({...spec,requestId:'phone-3'});
  q.claim('bench.code'); q.cancel(running.id);
  assert.equal(q.beat('bench.code',running.id,'ready').cancel,true);
  q.finish('bench.code',{id:running.id,state:'cancelled',result:'cancelled'});
  q.close();
});
