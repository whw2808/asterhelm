test('certificate ownership, third-device routing, task time and context membership survive restart',t=>{
  const home=mkdtempSync(join(tmpdir(),'registered-'));
  t.after(()=>rmSync(home,{recursive:true,force:true}));
  const db=join(home,'tasks.sqlite');
  let q=configuredQueue(db);
  assert.equal(new Set(q.workers().map(w=>w.deviceId)).size,2);
  const registration={deviceId:'studio',deviceName:'录音室',platform:'Linux',formFactor:'laptop',deviceAliases:['工作室'],target:'studio.voice',agentName:'Voice',kind:'voice',aliases:['音频'],capabilities:['read-only','contexts'],contextSources:['Codex CLI']};
  q.registry.register('cert:studio',registration);
  assert.throws(()=>q.registry.register('cert:studio',{...registration,formFactor:'../../asset'}));
  const {formFactor,...oldConnector}=registration;
  q.registry.register('cert:studio',oldConnector);
  assert.throws(()=>q.registry.register('cert:other',registration));
  assert.throws(()=>q.registry.register('cert:studio',{...registration,deviceId:'../../x'}));
  assert.throws(()=>q.registry.register('cert:studio',{...registration,target:'other.voice'}));
  assert.throws(()=>q.registry.authorizeTarget('cert:other',registration.target));
  assert.throws(()=>q.registry.authorizeTarget('cert:studio','bench.code'));
  assert.throws(()=>q.registry.authorizeDevice('cert:other',registration.deviceId));
  assert.throws(()=>q.submit({target:registration.target,mode:'workspace-write',prompt:'x'}));
  const task=q.submit({target:registration.target,prompt:'summarize',requestId:'one'});
  assert.equal(task.startedAt,null);
  assert.equal(q.claim(registration.target).id,task.id);
  const start=q.get(task.id).startedAt;
  assert.ok(start);
  q.beat(registration.target,task.id,'working','running_executor');
  const heartbeat=q.get(task.id).lastHeartbeatAt;
  assert.ok(heartbeat);
  assert.equal(q.list()[0].progress,'running_executor');
  const rx=new ContextReceiver(home);
  const {generation}=rx.plan('studio',{entries:[]});
  rx.commit('studio',{generation});
  assert.equal(contextCoverage(home).find(r=>r.machine==='studio').online,true);
  q.close();q=new Queue(db);
  assert.equal(q.claim(registration.target).startedAt,start);
  assert.equal(q.get(task.id).lastHeartbeatAt,heartbeat);
  q.finish(registration.target,{id:task.id,state:'succeeded',result:'ok'});
  const finished=q.get(task.id).finishedAt;
  assert.ok(finished);
  const board=groupBoard({workers:q.workers(),tasks:q.list(),sessions:[],coverage:contextCoverage(home)});
  assert.equal(board.machines.length,3);
  const studio=board.machines.find(device=>device.id==='studio');
  assert.equal(studio.name,'录音室');
  assert.equal(studio.formFactor,'laptop');
  assert.equal(studio.agents[0].tasks[0].finishedAt,finished);
  q.close();
});

test('two registered connectors can refresh different agents on one device independently',t=>{
  const home=mkdtempSync(join(tmpdir(),'context-scopes-'));
  t.after(()=>rmSync(home,{recursive:true,force:true}));
  const q=new Queue(join(home,'tasks.sqlite'));
  const descriptor={deviceId:'lab',deviceName:'Lab',platform:'Linux',agentName:'Assistant',kind:'custom',capabilities:['read-only','contexts']};
  const reg=(target,source)=>q.registry.register('cert:lab',{...descriptor,target,contextSources:[source]});
  reg('lab.code','Editor');reg('lab.art','Art Studio');
  assert.throws(()=>reg('lab.other','Editor'));
  const receiver=new ContextReceiver(home);
  const A={target:'lab.code',sources:['Editor']},B={target:'lab.art',sources:['Art Studio']};
  const stamp=new Date().toISOString();
  const row=(id,source)=>({id,title:source,cwd:'',source,summary:'',createdAt:stamp,updatedAt:stamp,status:'completed',lastMessageAt:null,sourceUpdatedAt:stamp,archived:false,visibility:'metadata-only',readOnly:true,evidence:[]});
  const a=row('00000000-0000-4000-8000-000000000001','Editor'),b=row('00000000-0000-4000-8000-000000000002','Art Studio');
  const plan=(scope,rows)=>receiver.plan('lab',{entries:rows.map(r=>[r.id,contextDigest(r)])},scope).generation;
  const ag=plan(A,[a]),bg=plan(B,[b]);
  assert.throws(()=>receiver.put('lab',{generation:bg,rows:[b]},A));
  receiver.put('lab',{generation:ag,rows:[a]},A);receiver.put('lab',{generation:bg,rows:[b]},B);
  receiver.commit('lab',{generation:bg},B);receiver.commit('lab',{generation:ag},A);
  assert.deepEqual(readContexts(home).map(r=>r.target).sort(),['lab.art','lab.code']);
  const rejected=plan(A,[b]);
  assert.throws(()=>receiver.put('lab',{generation:rejected,rows:[b]},A));
  receiver.commit('lab',{generation:plan(B,[])},B);
  assert.deepEqual(readContexts(home).map(r=>r.title),['Editor']);
  q.close();
});

test('hardware is bound to its authenticated subject and retains scope across equal names and project aliases',t=>{
  const home=mkdtempSync(join(tmpdir(),'hardware-scope-'));t.after(()=>rmSync(home,{recursive:true,force:true}));
  const file=join(home,'tasks.sqlite');let q=new Queue(file);
  const descriptor=(id)=>({deviceId:id,deviceName:'Compute',platform:'Linux',target:id+'.runner',agentName:'Runner',kind:'generic',capabilities:['read-only']});
  const a=descriptor('compute-a'),b=descriptor('compute-b');
  q.registry.register('cert:compute-a',a);q.registry.register('cert:compute-b',b);
  q.registry.setProjectAliases([{project:'catalog',alias:'build desk',deviceId:a.deviceId},{project:'index',alias:'build desk',deviceId:b.deviceId}]);
  const report={subjectDeviceId:a.deviceId,observedAt:new Date().toISOString(),scope:'container',scopeSource:'container-marker',platform:'linux',architecture:'x86_64',systemSource:'node:os',
    gpu:{status:'unknown',source:'nvidia-smi',devices:[]}};
  assert.throws(()=>q.registry.register('cert:compute-b',{...b,hardware:report}));
  assert.throws(()=>q.registry.recordHardware('cert:compute-b',a.target,report));
  assert.throws(()=>q.registry.recordHardware('cert:compute-a',a.target,{...report,subjectDeviceId:b.deviceId}));
  assert.throws(()=>q.registry.recordHardware('cert:compute-a',a.target,{...report,observedBy:b.target}));
  assert.throws(()=>q.registry.recordHardware('cert:compute-a',a.target,{...report,systemSource:'session text'}));
  q.registry.recordHardware('cert:compute-a',a.target,report);
  q.close();q=new Queue(file);
  const [first,second]=q.workers();
  assert.equal(first.hardware.observedBy,a.target);assert.equal(first.hardware.subjectDeviceId,a.deviceId);
  assert.equal(first.hardware.scope,'container');assert.equal(first.hardware.gpu.status,'unknown');assert.equal(second.hardware,null);
  q.registry.recordHardware('cert:compute-b',b.target,{...report,subjectDeviceId:b.deviceId,gpu:{status:'none-visible',source:'nvidia-smi',devices:[]}});
  assert.equal(q.registry.get(b.target).hardware.gpu.status,'none-visible');
  assert.deepEqual(projectAliasesFor(first,'index'),[]);assert.deepEqual(projectAliasesFor(first,'catalog'),['build desk']);
  assert.deepEqual(projectAliasesFor(second,'catalog'),[]);assert.deepEqual(projectAliasesFor(second,'index'),['build desk']);
  assert.deepEqual(first.projectAliases,[{project:'catalog',alias:'build desk'}]);assert.deepEqual(second.projectAliases,[{project:'index',alias:'build desk'}]);q.close();
});
